import type { jsPDF } from 'jspdf';
import { getRideDestinations } from '../data/destinations';
import { getItineraryStops } from '../data/itinerary';
import type { TripRecord } from '../data/trips';

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const PAGE_MARGIN = 44;
const CONTENT_WIDTH = PAGE_WIDTH - PAGE_MARGIN * 2;

type PdfColor = [number, number, number];

const COLORS: Record<'green' | 'dark' | 'muted' | 'line' | 'soft' | 'white' | 'accent', PdfColor> = {
  green: [48, 112, 82],
  dark: [23, 65, 53],
  muted: [91, 117, 102],
  line: [222, 234, 226],
  soft: [242, 247, 243],
  white: [255, 255, 255],
  accent: [217, 180, 103],
};

const MODE_NAMES: Record<string, string> = {
  tricycle: 'Tricycle',
  natsco: 'NATSCO',
  vodactco: 'VODACTCO',
  jeepney: 'Jeepney',
  multicab: 'Multicab',
};

const STATUS_LABELS: Record<TripRecord['status'], string> = {
  upcoming: 'Upcoming',
  ongoing: 'Ongoing',
  completed: 'Completed',
  cancelled: 'Cancelled',
};

function setTextColor(doc: jsPDF, color: PdfColor) {
  doc.setTextColor(color[0], color[1], color[2]);
}

function setFillColor(doc: jsPDF, color: PdfColor) {
  doc.setFillColor(color[0], color[1], color[2]);
}

function setDrawColor(doc: jsPDF, color: PdfColor) {
  doc.setDrawColor(color[0], color[1], color[2]);
}

function pdfAmount(amount: number) {
  return `PHP ${amount.toLocaleString('en-PH', { maximumFractionDigits: 2 })}`;
}

function dateLabel(value?: string) {
  if (!value) return 'Date not recorded';
  const date = new Date(`${value}T00:00:00`);
  return Number.isNaN(date.getTime())
    ? 'Date not recorded'
    : date.toLocaleDateString('en-PH', { month: 'long', day: 'numeric', year: 'numeric' });
}

function durationLabel(trip: TripRecord) {
  const ms = typeof trip.durationMs === 'number'
    ? trip.durationMs
    : trip.startedAt && trip.completedAt
      ? Date.parse(trip.completedAt) - Date.parse(trip.startedAt)
      : null;
  if (ms === null || !Number.isFinite(ms) || ms < 0) return 'Not recorded';
  if (ms < 60000) return '<1 min';
  const totalMinutes = Math.floor(ms / 60000);
  return totalMinutes >= 60 ? `${Math.floor(totalMinutes / 60)} h ${totalMinutes % 60} min` : `${totalMinutes} min`;
}

export function tripPdfFilename(trip: TripRecord): string {
  const slug = (trip.itinerary.tripName || 'completed-trip')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
  const date = trip.itinerary.travelDate || trip.completedAt?.slice(0, 10) || new Date().toISOString().slice(0, 10);
  return `ride-${slug || 'trip'}-${date}.pdf`;
}

export async function createTripPdf(trip: TripRecord, generatedAt = new Date()): Promise<{ doc: jsPDF; filename: string }> {
  const { jsPDF: PdfDocument } = await import('jspdf');
  const doc = new PdfDocument({ unit: 'pt', format: 'a4', compress: true });
  const places = getRideDestinations();
  const tripPlaces = getItineraryStops(trip.itinerary);
  const visitedPlaces = tripPlaces.filter((place) => trip.visitedStopIds.includes(place.id));
  const startPlace = places.find((place) => place.id === trip.selectedRoute?.fromId) ?? tripPlaces[0];
  const finalPlace = places.find((place) => place.id === trip.selectedRoute?.toId) ?? tripPlaces.at(-1);
  const expenses = Object.entries(trip.actualExpenses ?? {})
    .filter(([, amount]) => typeof amount === 'number' && Number.isFinite(amount) && amount >= 0);
  const actualTotal = expenses.length ? expenses.reduce((sum, [, amount]) => sum + amount, 0) : null;
  const estimatedValues = [...Object.values(trip.itinerary.budget), ...Object.values(trip.itinerary.estimatedCosts)]
    .filter((amount): amount is number => typeof amount === 'number' && Number.isFinite(amount) && amount >= 0);
  const estimatedTotal = estimatedValues.length ? estimatedValues.reduce((sum, amount) => sum + amount, 0) : null;

  let y = 0;

  function setFont(style: 'normal' | 'bold', size: number, color: PdfColor) {
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    setTextColor(doc, color);
  }

  function drawPageChrome(pageNumber: number, pageCount: number) {
    if (pageNumber > 1) {
      setFillColor(doc, COLORS.green);
      doc.rect(0, 0, PAGE_WIDTH, 8, 'F');
      setFont('bold', 9, COLORS.dark);
      doc.text('RIDE', PAGE_MARGIN, 34);
      setFont('normal', 8, COLORS.muted);
      doc.text('TRIP RECEIPT', PAGE_MARGIN + 34, 34);
      setDrawColor(doc, COLORS.line);
      doc.setLineWidth(0.7);
      doc.line(PAGE_MARGIN, 46, PAGE_WIDTH - PAGE_MARGIN, 46);
    }

    setDrawColor(doc, COLORS.line);
    doc.setLineWidth(0.7);
    doc.line(PAGE_MARGIN, PAGE_HEIGHT - 48, PAGE_WIDTH - PAGE_MARGIN, PAGE_HEIGHT - 48);
    setFont('normal', 8, COLORS.muted);
    doc.text(`Generated by RIDE · ${generatedAt.toLocaleDateString('en-PH')}`, PAGE_MARGIN, PAGE_HEIGHT - 30);
    doc.text(`PAGE ${pageNumber} OF ${pageCount}`, PAGE_WIDTH - PAGE_MARGIN, PAGE_HEIGHT - 30, { align: 'right' });
  }

  function newPage() {
    doc.addPage();
    y = 68;
  }

  function ensureSpace(height: number) {
    if (y + height > PAGE_HEIGHT - 66) newPage();
  }

  function section(title: string) {
    ensureSpace(38);
    setFont('bold', 8, COLORS.green);
    doc.text(title.toUpperCase(), PAGE_MARGIN, y);
    setDrawColor(doc, COLORS.line);
    doc.setLineWidth(0.8);
    doc.line(PAGE_MARGIN, y + 7, PAGE_WIDTH - PAGE_MARGIN, y + 7);
    y += 24;
  }

  function note(text: string) {
    setFont('normal', 9, COLORS.muted);
    const lines = doc.splitTextToSize(text, CONTENT_WIDTH);
    ensureSpace(lines.length * 13 + 12);
    doc.text(lines, PAGE_MARGIN, y);
    y += lines.length * 13 + 12;
  }

  function routeCard(x: number, top: number, width: number, label: string, name: string, address: string) {
    const textWidth = width - 28;
    setFont('bold', 11, COLORS.dark);
    const nameLines = doc.splitTextToSize(name, textWidth);
    setFont('normal', 8.5, COLORS.muted);
    const addressLines = doc.splitTextToSize(address, textWidth);
    const height = Math.max(78, 40 + nameLines.length * 13 + addressLines.length * 11);

    setFillColor(doc, COLORS.soft);
    setDrawColor(doc, COLORS.line);
    doc.roundedRect(x, top, width, height, 9, 9, 'FD');
    setFont('bold', 7, COLORS.green);
    doc.text(label.toUpperCase(), x + 14, top + 18);
    setFont('bold', 11, COLORS.dark);
    doc.text(nameLines, x + 14, top + 37);
    setFont('normal', 8.5, COLORS.muted);
    doc.text(addressLines, x + 14, top + 37 + nameLines.length * 13 + 2);
    return height;
  }

  doc.setProperties({
    title: `${trip.itinerary.tripName || 'Trip'} receipt`,
    subject: 'RIDE completed trip receipt',
    creator: 'RIDE',
  });

  setFillColor(doc, COLORS.dark);
  doc.rect(0, 0, PAGE_WIDTH, 128, 'F');
  setFillColor(doc, COLORS.green);
  doc.rect(0, 119, PAGE_WIDTH, 9, 'F');
  setFillColor(doc, COLORS.accent);
  doc.roundedRect(PAGE_WIDTH - 116, 22, 72, 22, 10, 10, 'F');
  setTextColor(doc, COLORS.white);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(24);
  doc.text('RIDE', PAGE_MARGIN, 48);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('TRIP RECEIPT', PAGE_MARGIN, 66);
  doc.setFontSize(8);
  doc.text(generatedAt.toLocaleDateString('en-PH', { month: 'long', day: 'numeric', year: 'numeric' }), PAGE_WIDTH - PAGE_MARGIN, 59, { align: 'right' });
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  setTextColor(doc, COLORS.dark);
  doc.text(STATUS_LABELS[trip.status].toUpperCase(), PAGE_WIDTH - 80, 36, { align: 'center' });
  y = 158;

  setFont('bold', 19, COLORS.dark);
  const titleLines = doc.splitTextToSize(trip.itinerary.tripName || 'Completed trip', CONTENT_WIDTH);
  doc.text(titleLines, PAGE_MARGIN, y);
  y += titleLines.length * 23 + 4;
  setFont('normal', 9, COLORS.muted);
  doc.text(dateLabel(trip.itinerary.travelDate), PAGE_MARGIN, y);
  setFont('normal', 8, COLORS.muted);
  doc.text(`RECEIPT  ${trip.id.slice(0, 8).toUpperCase()}`, PAGE_WIDTH - PAGE_MARGIN, y, { align: 'right' });
  y += 24;

  section('Route');
  const routeGap = 12;
  const routeWidth = (CONTENT_WIDTH - routeGap) / 2;
  const routeHeight = Math.max(
    routeCard(PAGE_MARGIN, y, routeWidth, 'Starting point', startPlace?.name ?? 'Origin', startPlace?.address ?? 'Address not recorded'),
    routeCard(PAGE_MARGIN + routeWidth + routeGap, y, routeWidth, 'Final destination', finalPlace?.name ?? 'Destination', finalPlace?.address ?? 'Address not recorded'),
  );
  y += routeHeight + 20;

  const facts = [
    ['Transport', trip.selectedRoute ? MODE_NAMES[trip.selectedRoute.mode] ?? trip.selectedRoute.mode : 'Not recorded'],
    ['Duration', durationLabel(trip)],
    ['Stops visited', `${visitedPlaces.length} of ${tripPlaces.length}`],
    ['Travelers', String(Math.max(1, trip.itinerary.travelerCount || 1))],
  ];
  const factGap = 10;
  const factWidth = (CONTENT_WIDTH - factGap) / 2;
  const factHeight = 45;
  ensureSpace(factHeight * 2 + factGap + 12);
  facts.forEach(([label, value], index) => {
    const x = PAGE_MARGIN + (index % 2) * (factWidth + factGap);
    const factY = y + Math.floor(index / 2) * (factHeight + factGap);
    setFillColor(doc, COLORS.soft);
    doc.roundedRect(x, factY, factWidth, factHeight, 8, 8, 'F');
    setFont('bold', 7, COLORS.muted);
    doc.text(label.toUpperCase(), x + 12, factY + 16);
    setFont('bold', 10, COLORS.dark);
    const valueLines = doc.splitTextToSize(value, factWidth - 24).slice(0, 1);
    doc.text(valueLines, x + 12, factY + 33);
  });
  y += factHeight * 2 + factGap + 20;

  section('Places visited');
  if (!tripPlaces.length) {
    note('No stops were recorded for this trip.');
  } else {
    tripPlaces.forEach((place, index) => {
      const visited = trip.visitedStopIds.includes(place.id);
      const status = visited ? 'Visited' : 'Not visited';
      const textWidth = CONTENT_WIDTH - 66 - 86;
      setFont('bold', 10, COLORS.dark);
      const nameLines = doc.splitTextToSize(place.name, textWidth);
      setFont('normal', 8, COLORS.muted);
      const addressLines = doc.splitTextToSize(`${place.address}, ${place.city}`, textWidth);
      const rowHeight = Math.max(50, 20 + nameLines.length * 12 + addressLines.length * 10);
      ensureSpace(rowHeight + 6);

      const rowY = y;
      setFillColor(doc, COLORS.soft);
      setDrawColor(doc, COLORS.line);
      doc.roundedRect(PAGE_MARGIN, rowY, CONTENT_WIDTH, rowHeight, 8, 8, 'FD');
      setFillColor(doc, COLORS.green);
      doc.circle(PAGE_MARGIN + 19, rowY + rowHeight / 2, 10, 'F');
      setFont('bold', 8, COLORS.white);
      doc.text(String(index + 1), PAGE_MARGIN + 19, rowY + rowHeight / 2 + 3, { align: 'center' });
      setFont('bold', 10, COLORS.dark);
      doc.text(nameLines, PAGE_MARGIN + 38, rowY + 18);
      setFont('normal', 8, COLORS.muted);
      doc.text(addressLines, PAGE_MARGIN + 38, rowY + 18 + nameLines.length * 12);
      const statusWidth = doc.getTextWidth(status) + 14;
      const statusX = PAGE_WIDTH - PAGE_MARGIN - statusWidth - 10;
      setFillColor(doc, visited ? [225, 241, 231] : [235, 238, 236]);
      doc.roundedRect(statusX, rowY + 11, statusWidth, 18, 8, 8, 'F');
      setFont('bold', 7, visited ? COLORS.green : COLORS.muted);
      doc.text(status.toUpperCase(), statusX + statusWidth / 2, rowY + 23, { align: 'center' });
      y = rowY + rowHeight + 6;
    });
    y += 10;
  }

  section('Costs');
  if (expenses.length && actualTotal !== null) {
    ensureSpace(62);
    setFillColor(doc, COLORS.dark);
    doc.roundedRect(PAGE_MARGIN, y, CONTENT_WIDTH, 48, 9, 9, 'F');
    setFont('normal', 8, COLORS.white);
    doc.text('TOTAL SPENT', PAGE_MARGIN + 14, y + 19);
    setFont('bold', 15, COLORS.white);
    doc.text(pdfAmount(actualTotal), PAGE_WIDTH - PAGE_MARGIN - 14, y + 30, { align: 'right' });
    y += 60;
    expenses.forEach(([label, amount]) => {
      ensureSpace(28);
      setFont('normal', 9, COLORS.muted);
      doc.text(label.replace(/[_-]+/g, ' ').replace(/\b\w/g, (letter) => letter.toUpperCase()), PAGE_MARGIN + 2, y);
      setFont('bold', 9, COLORS.dark);
      doc.text(pdfAmount(amount), PAGE_WIDTH - PAGE_MARGIN - 2, y, { align: 'right' });
      y += 10;
      setDrawColor(doc, COLORS.line);
      doc.setLineWidth(0.6);
      doc.line(PAGE_MARGIN, y, PAGE_WIDTH - PAGE_MARGIN, y);
      y += 13;
    });
  } else {
    note('No expenses were recorded for this trip.');
  }

  if (estimatedTotal !== null) {
    setFont('normal', 9, COLORS.muted);
    const estimateText = `Planned estimate: ${pdfAmount(estimatedTotal)}${actualTotal === null ? ' (no actual spending recorded)' : ''}`;
    const estimateLines = doc.splitTextToSize(estimateText, CONTENT_WIDTH);
    ensureSpace(estimateLines.length * 13 + 10);
    doc.text(estimateLines, PAGE_MARGIN, y);
    y += estimateLines.length * 13 + 10;
  }

  if (trip.selectedRoute?.fareReference) {
    setFont('normal', 9, COLORS.muted);
    const fareLines = doc.splitTextToSize(`Fare reference: ${trip.selectedRoute.fareReference}`, CONTENT_WIDTH);
    ensureSpace(fareLines.length * 13 + 10);
    doc.text(fareLines, PAGE_MARGIN, y);
    y += fareLines.length * 13 + 10;
  }

  const pageCount = doc.getNumberOfPages();
  for (let pageNumber = 1; pageNumber <= pageCount; pageNumber += 1) {
    doc.setPage(pageNumber);
    drawPageChrome(pageNumber, pageCount);
  }
  return { doc, filename: tripPdfFilename(trip) };
}

export async function downloadTripPdf(
  trip: TripRecord,
  generatedAt = new Date(),
  previewWindow?: Pick<Window, 'location'>,
): Promise<void> {
  const { doc, filename } = await createTripPdf(trip, generatedAt);
  if (previewWindow) {
    const blob = doc.output('blob');
    if (/CriOS\/[\d]+/.test(navigator.userAgent)) {
      previewWindow.location.href = await readBlobAsDataUrl(blob);
    } else {
      const blobUrl = URL.createObjectURL(blob);
      previewWindow.location.href = blobUrl;
      window.setTimeout(() => URL.revokeObjectURL(blobUrl), 40000);
    }
    return;
  }
  doc.save(filename);
}

function readBlobAsDataUrl(blob: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      if (typeof reader.result === 'string') resolve(reader.result);
      else reject(new Error('The PDF could not be opened in this browser.'));
    };
    reader.onerror = () => reject(new Error('The PDF could not be opened in this browser.'));
    reader.readAsDataURL(blob);
  });
}
